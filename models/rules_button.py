"""Кнопки для правил сервера с большим изображением"""
import discord

class RulesButton(discord.ui.View):
    """Класс для отображения правил с кнопкой-ссылкой"""

    def __init__(self):
        super().__init__(timeout=None)

    @discord.ui.button(label='Просмотреть правила сервера', style=discord.ButtonStyle.primary,
                       custom_id="view_rules_btn")
    async def view_rules(self, interaction: discord.Interaction, button: discord.ui.Button):
        """Здесь вы пишете текст ваших правил"""
        rules_text = (
            " **ПРАВИЛА НАШЕГО СЕРВЕРА**\n\n"
            "**1. Общие положения**\n"
            "• **Уважительное общение:** Запрещены оскорбления, травля, угрозы, дискриминация по любым признакам.\n"
            "• **Запрет NSFW-контента:** Строго запрещено распространение порнографии, шок-контента и сцен жестокости.\n"
            "• **Нет спаму и саморекламе:** Запрещен флуд, капс, спам эмодзи и реклама сторонних проектов.\n"
            "• **Язык сервера:** Основной язык общения — русский.\n"
            "• **Конфиденциальность:** Запрещена публикация личных данных других участников (доксинг).\n\n"

            "**2. Правила каналов**\n"
            "• **Тематика:** Общайтесь строго в соответствующих каналах.\n"
            "• **Голосовой этикет:** Запрещено шуметь, кричать и использовать софт для изменения голоса.\n"
            "• **Никнеймы:** Имя не должно содержать мат, оскорбления или имитировать администрацию.\n\n"

            "**3. Администрация и ответственность**\n"
            "• **Модерация:** Администрация имеет право выдавать муты и баны на свое усмотрение.\n"
            "• **Обход бана:** Использование вторых аккаунтов для обхода наказания карается перманентным баном.\n"
            "• **Спорные ситуации:** В ситуациях, не описанных правилами, решение принимает администрация.\n\n"
            "*Желаем приятной игры!*"
        )

        # Отправляем правила только нажавшему (ephemeral=True)
        await interaction.response.send_message(rules_text, ephemeral=True)

    @classmethod
    async def send_rules(cls, interaction_or_ctx):
        """Метод для удобной отправки сообщения с локальной картинкой и кнопкой"""

        file = discord.File("assets/rules.jpg", filename="rules.jpg")

        embed = discord.Embed(
            title="Правила сервера",
            description="Пожалуйста, ознакомьтесь с правилами нашего сообщества:",
            color=discord.Color.blue()
        )

        # 2. Привязываем картинку к эмбеду через название файла
        embed.set_image(url="attachment://rules.jpg")

        # 3. Отправляем и файл, и эмбед вместе
        if isinstance(interaction_or_ctx, discord.Interaction):
            await interaction_or_ctx.response.send_message(file=file, embed=embed, view=cls())
        else:
            await interaction_or_ctx.send(file=file, embed=embed, view=cls())

